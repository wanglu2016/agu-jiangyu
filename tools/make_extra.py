by_name = {}
for c in data['co']:
    by_name.setdefault(c[1], []).append(c[0])

def codes(names):
    out = []
    for n in names:
        if n not in by_name:
            print('  名单里的公司不在数据中，已跳过：', n); continue
        if len(by_name[n]) > 1:
            raise SystemExit('重名公司，请改用代码：' + n)
        out.append(by_name[n][0])
    return out

